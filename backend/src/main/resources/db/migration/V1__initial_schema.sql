-- The schema as it existed before Flyway was introduced.
-- Existing databases are baselined at version 1 and skip this file; only empty databases run it.

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password_hash varchar(255) NOT NULL,
    role varchar(255) NOT NULL,
    username varchar(255) NOT NULL,
    CONSTRAINT ukr43af9ap4edm43mmtq01oddj6 UNIQUE (username)
);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode varchar(255),
    low_stock_threshold integer NOT NULL,
    name varchar(255) NOT NULL,
    price numeric(38,2),
    stock integer NOT NULL,
    updated_at timestamp(6) with time zone,
    active boolean DEFAULT true NOT NULL,
    CONSTRAINT products_stock_check CHECK (stock >= 0),
    CONSTRAINT ukqfr8vf85k3q1xinifvsl1eynf UNIQUE (barcode)
);

CREATE TABLE sales (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id uuid NOT NULL,
    created_at timestamp(6) with time zone,
    discount numeric(38,2),
    subtotal numeric(38,2),
    total numeric(38,2),
    cashier_id bigint,
    CONSTRAINT ukrgt6teoe380keyp2291m8ba3q UNIQUE (client_id),
    CONSTRAINT fktbqsuaq9mtds03lxuiub7m4b1 FOREIGN KEY (cashier_id) REFERENCES users (id)
);

CREATE TABLE sale_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qty integer NOT NULL,
    unit_price numeric(38,2),
    product_id bigint NOT NULL,
    sale_id bigint NOT NULL,
    CONSTRAINT fk8g0sjiqs7tg055o06p6wawu39 FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk7tcpbc5c5mpnm8fl2phl8ep7l FOREIGN KEY (sale_id) REFERENCES sales (id)
);

CREATE TABLE stock_adjustments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone,
    delta integer NOT NULL,
    performed_by varchar(255),
    reason varchar(255),
    role varchar(255),
    stock_after integer NOT NULL,
    product_id bigint NOT NULL,
    CONSTRAINT fkh0emjv0ifyv4bpghf1pfcaue4 FOREIGN KEY (product_id) REFERENCES products (id)
);
